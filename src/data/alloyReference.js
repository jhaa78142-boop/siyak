// Builds a variant entry for a product line: takes the shared alloy record and
// layers on the product-form-specific name, size range and description so the
// same chemistry never needs to be retyped for pipes vs fittings vs bar etc.
export function alloyVariant(alloy, { name, sizes, form, desc, type, schedule, end, length }) {
  return {
    name,
    grades: [alloy.grade, alloy.spec],
    sizes,
    desc: desc || alloy.blurb,
    chem: alloy.chem || undefined,
    standardsEquiv: alloy.standardsEquiv || undefined,
    form,
    type,
    schedule,
    end,
    length,
  };
}
