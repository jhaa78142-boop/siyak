const I18nContext = createContext(null);
const STORAGE_KEY = "medimind-language";
const languageCodes = new Set(supportedLanguages.map(({ code }) => code));

function getSavedLanguage() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    return languageCodes.has(saved) ? saved : "en";
  } catch {
    return "en";
  }
}

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(getSavedLanguage);
  const activeLanguage = supportedLanguages.find(({ code }) => code === language) || supportedLanguages[0];

  useEffect(() => {
    document.documentElement.lang = activeLanguage.code;
    document.documentElement.dir = activeLanguage.dir;
    try {
      window.localStorage.setItem(STORAGE_KEY, activeLanguage.code);
    } catch {
      // The selected language still applies for this page view when storage is unavailable.
    }
  }, [activeLanguage]);

  const value = useMemo(() => ({
    language: activeLanguage.code,
    setLanguage,
    t: (key) => translations[activeLanguage.code]?.[key] || additionalTranslations[activeLanguage.code]?.[key] || key,
  }), [activeLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider.");
  return context;
}
